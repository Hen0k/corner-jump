#!/usr/bin/env python3
"""Build the chat widget from widget/src.html and the levels in game.js.

Writes:
  widget/widget.html   the HTML the bot sends (must stay under 4096 bytes after zlib -9)
  widget/preview.html  the same widget with a stand-in TelegramWidget, for checking in a browser
  bot/widget.js        widget.html as a JS module, imported by the Cloudflare Worker

Run from anywhere: python3 tools/widget/build.py
"""
import json, re, sys, zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIMIT_ZLIB, LIMIT_RAW = 4096, 32768


def bit(square):
    x, y = "abcdefgh".index(square[0]), int(square[1:]) - 1
    assert (x + y) % 2 == 0, f"{square} is not a dark square"
    return y * 4 + x // 2


def mask(squares):
    m = 0
    for s in squares.split():
        m |= 1 << bit(s)
    return m


def b36(n):
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    out = ""
    while True:
        n, r = divmod(n, 36)
        out = digits[r] + out
        if not n:
            return out


def levels():
    src = (ROOT / "game.js").read_text()
    found = re.findall(r'tier:\s*"(\w+)",\s*pieces:\s*"([^"]+)",\s*open:\s*"([^"]+)"', src)
    if not found:
        sys.exit("No levels found in game.js")
    tiers = "".join({"Easy": "E", "Medium": "M", "Hard": "H", "Expert": "X"}[t] for t, _, _ in found)
    codes = " ".join(f"{b36(mask(p))}.{b36(mask(o))}" for _, p, o in found)
    return codes, tiers


def minify(html):
    html = re.sub(r"<!--.*?-->", "", html, flags=re.S)
    lines = []
    for line in html.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        lines.append(line)
    return "\n".join(lines)


STUB = """<style>:root{--tg-theme-bg-color:#fff;--tg-theme-text-color:#000;--tg-theme-hint-color:#999;--tg-theme-secondary-bg-color:#f1f1f1}
body{max-width:360px;margin:20px auto!important;border:1px solid #ccc;border-radius:14px;overflow:hidden}</style>
<script>window.TelegramWidget={profile:1,colorScheme:'light',isPreview:false,isForward:false,chatType:'private',
viewer:{id:1,first_name:'Test'},chatData:null,publicData:null,wallet:null,_h:{},
onEvent(e,f){this._h[e]=f},ready(){},openLink:console.log,openTelegramLink:console.log,copyText:console.log,
HapticFeedback:{impactOccurred(){return this},notificationOccurred(){return this},selectionChanged(){return this}},
request(d){console.log('request',d);window.lastRequest=d;return Promise.resolve({result:null})}};</script>
"""


def main():
    codes, tiers = levels()
    html = (ROOT / "widget" / "src.html").read_text()
    html = minify(html.replace("__LEVELS__", codes).replace("__TIERS__", tiers))
    raw = len(html.encode())
    packed = len(zlib.compress(html.encode(), 9))
    print(f"{len(tiers)} levels, {raw} bytes raw, {packed} bytes after zlib -9 (limits {LIMIT_RAW} / {LIMIT_ZLIB})")
    if raw > LIMIT_RAW or packed > LIMIT_ZLIB:
        sys.exit("Widget is too large for Telegram")
    (ROOT / "widget" / "widget.html").write_text(html)
    (ROOT / "widget" / "preview.html").write_text("<!doctype html><meta charset=utf-8><title>Corner Jump widget preview</title>\n" + STUB + html)
    (ROOT / "bot" / "widget.js").write_text("// Generated by tools/widget/build.py from widget/src.html. Do not edit.\nexport default " + json.dumps(html) + ";\n"
        f"export const LEVEL_COUNT = {len(tiers)};\n")


if __name__ == "__main__":
    main()
